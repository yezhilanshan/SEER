@torch.no_grad()
def build_event_features(frontend,index,output):
    output=Path(output); output.mkdir(parents=True,exist_ok=False)
    device=next(frontend.parameters()).device
    former,p=frontend.event_former,frontend.semantic_projection
    prompt=former.build_prompt_cache(1)
    by_record=defaultdict(list)
    for run in index['runs']:
        by_record[run['record_uid']].append(run)
    events=[]
    for row in index['records']:
        if file_sha(row['path'])!=row['sha256']:
            raise ValueError('current-gate encoder cache source SHA changed')
        record=torch.load(row['path'],map_location='cpu',weights_only=False)
        for run in by_record[row['uid']]:
            radar=record['radar'][run['start']:run['end']].to(device)
            mask=record['radar_mask'][run['start']:run['end']].to(device)
            state=former.initial_state(1); ages={}
            for i in range(len(radar)):
                state=former.stream_update(state,radar[i:i+1],1.,mask[i:i+1],prompt).event_tokens
                if i<11:
                    ages[i+1]=p(state)[0].float().cpu()
            commit=former.commit_refine(radar.flatten(0,1)[None],mask.flatten()[None],prompt).event_tokens
            frame_mask=record['frame_target_mask'][run['start']*2:run['end']*2].clone()
            compatible=former.state_gate.architecture=='v25-age-free-positive-coordinate-v1'
            if compatible:
                # These two statistics require a previous visible frame.
                # The first frame's global predecessor lies outside the event.
                frame_mask[0,2:]=False
            target,target_mask=mean_evidence_target(record['frame_target'][run['start']*2:run['end']*2].numpy(),
                frame_mask.numpy())
            events.append(dict(**run,stream_tokens=state[0].float().cpu(),commit_tokens=commit[0].float().cpu(),
                stream_key=p(state)[0].float().cpu(),commit_key=p(commit)[0].float().cpu(),age_keys=ages,
                stream_visible_range=[run['start'],run['end']],commit_visible_range=[run['start'],run['end']],
                stream_target_range=[2*run['start'],2*run['end']],commit_target_range=[2*run['start'],2*run['end']],
                cross_boundary_delta_excluded=compatible,
                target=torch.from_numpy(target),target_mask=torch.from_numpy(target_mask)))
        print(json.dumps(dict(phase='current-gate-features',recording=row['uid'])),flush=True)
    torch.save(dict(events=events,frontend_digest=module_digest(frontend),schema_version=25,
        architecture=frontend.event_former.state_gate.architecture),output/'events.pt')
    write_json(output/'manifest.json',dict(frontend_digest=module_digest(frontend),events=len(events),
        architecture=frontend.event_former.state_gate.architecture,
        events_sha256=file_sha(output/'events.pt'),by_role={role:sum(r['role']==role for r in events) for role in ('fit','dev')}))
    return events


def build_oracle_pairs(events):
    fit=[e for e in events if e['role']=='fit' and len(e['age_keys'])>=6]
    pairs=[]
    for event_index,event in enumerate(fit):
        peers=[p for p in fit if p['subject_id']==event['subject_id'] and p['sensor_id']==event['sensor_id']]
        selected=[]
        for label in sorted({p['label'] for p in peers}):
            choices=[p for p in peers if p['label']==label]
            # Deterministic two-run rotation per reference/class bounds RAM;
            # repeated pair draws remain repeat draws, never extra subjects.
            offset=event_index%len(choices)
            selected.extend(choices[(offset+i)%len(choices)] for i in range(min(2,len(choices))))
        for candidate in selected:
            # Same actions include distinct physical runs and their own initial
            # prefix; unlike actions are never generated by shifting labels.
            target=int(event['label']!=candidate['label'])
            for age,key in candidate['age_keys'].items():
                bucket=0 if age<=3 else 1 if age<=6 else 2 if age<=9 else 3
                pairs.append(dict(active=event['stream_key'],candidate=key,target=target,age_bucket=bucket,
                    age_seconds=(age-1)*.18,subject_id=event['subject_id'],sensor_id=event['sensor_id'],
                    episode_id=f"oracle:{event['uid']}:{candidate['uid']}",source_event=event['uid'],candidate_event=candidate['uid']))
    return pairs


class PairSampler:
    def __init__(self,pairs,*,seed):
        self.rng=random.Random(seed)
        self.cells=defaultdict(list)
        self.subjects=sorted({r['subject_id'] for r in pairs})
        self.sensors=sorted({r['sensor_id'] for r in pairs})
        self.draw=0
        self.draw_counts=defaultdict(int)
        for pair in pairs:
            self.cells[(pair['subject_id'],pair['sensor_id'],pair['age_bucket'],pair['target'])].append(pair)
        missing=[(s,sensor,age,label) for s in self.subjects for sensor in self.sensors for age in range(4)
                 for label in (0,1) if not self.cells[(s,sensor,age,label)]]
        if not pairs or missing:
            raise ValueError(f'missing balanced subject/sensor/age/class cells: {missing}')

    def batch(self,device,size=64):
        if size!=64:
            raise ValueError('locked semantic batch64 required')
        selected=[]
        # Every group of8 contains all four age buckets and both classes.
        # Subject/sensor cycles run across batches independently of this axis.
        for i in range(size):
            j=self.draw+i
            cell_index=j//8
            subject=self.subjects[cell_index%len(self.subjects)]
            sensor=self.sensors[(cell_index//len(self.subjects))%len(self.sensors)]
            age=(i//2)%4; label=i%2
            cell=(subject,sensor,age,label)
            selected.append(self.rng.choice(self.cells[cell]))
            self.draw_counts[cell]+=1
        self.draw+=size
        return dict(active=torch.stack([r['active'] for r in selected]).to(device),
            candidate=torch.stack([r['candidate'] for r in selected]).to(device),
            target=torch.tensor([r['target'] for r in selected],dtype=torch.float32,device=device),
            age_bucket=torch.tensor([r['age_bucket'] for r in selected],device=device))

    def coverage(self):
        return [dict(subject=s,sensor=sensor,age_bucket=age,target=label,
            independent_candidates=len({r['episode_id'] for r in rows}),observations=len(rows),
            draws=self.draw_counts[(s,sensor,age,label)]) for (s,sensor,age,label),rows in sorted(self.cells.items())]


def save_head_checkpoint(stage,optimizer,output,phase,step,source):
    path=Path(output)/f'{phase}-step{step}.pt'
    if path.exists():
        raise FileExistsError('head checkpoint already exists')
    torch.save(dict(schema_version=25,phase=phase,step=step,stage_state=stage.state_dict(),
        optimizer=optimizer.state_dict(),optimizer_steps=dict(stage.optimizer_steps),source=source,
        code_digest=code_digest(),rng_state=torch.get_rng_state(),cuda_rng_state=torch.cuda.get_rng_state_all()),path)
    payload=torch.load(path,map_location='cpu',weights_only=False)
    counts=[int(v['step']) for v in payload['optimizer']['state'].values() if 'step' in v]
    if not counts or any(v!=step for v in counts):
        raise RuntimeError('head AdamW saved readback mismatch')
    return dict(path=str(path),sha256=file_sha(path),step=step,adamw_counts=sorted(set(counts)))


def train_fixed_head(stage,batch_builder,*,phase,steps,output,source,on_step=None):
    phase_steps={'evidence':500,'physical':1000,'oracle':250,'semantic':1000}
    if steps!=phase_steps.get(phase):
        raise ValueError('locked phase budget required')
    output=Path(output); output.mkdir(parents=True,exist_ok=False)
    stage.set_phase(phase); stage.train()
    parameters=[p for p in stage.parameters() if p.requires_grad]
    frozen={name:p.detach().cpu().clone() for name,p in stage.named_parameters() if not p.requires_grad}
    optimizer=torch.optim.AdamW(parameters,lr=1e-3,weight_decay=.01)
    checkpoints=[]
    try:
        with (output/'training.jsonl').open('x',encoding='utf-8') as log:
            for step in range(1,steps+1):
                optimizer.zero_grad(set_to_none=True)
                loss=batch_builder(stage)
                if not torch.isfinite(loss):
                    raise RuntimeError('nonfinite head loss; optimizer not updated')
                loss.backward()
                norm=torch.nn.utils.clip_grad_norm_(parameters,1.)
                if not torch.isfinite(norm):
                    raise RuntimeError('nonfinite head gradient; optimizer not updated')
                optimizer.step()
                counts=[int(v['step']) for v in optimizer.state.values() if 'step' in v]
                if not counts or any(value!=step for value in counts):
                    raise RuntimeError('head actual optimizer count mismatch')
                stage.optimizer_steps['semantic' if phase=='oracle' else phase]+=1
                row=dict(phase=phase,step=step,loss=float(loss.detach()),actual_optimizer_steps=step)
                log.write(json.dumps(row)+'\n'); log.flush()
                if on_step is not None:
                    on_step(row)
                if step%20==0 or step==1:
                    print(json.dumps(row),flush=True)
                if step in {100,500,steps}:
                    checkpoints.append(save_head_checkpoint(stage,optimizer,output,phase,step,source))
        if any(not torch.equal(p.detach().cpu(),frozen[name]) for name,p in stage.named_parameters() if name in frozen):
            raise RuntimeError('frozen head changed')
        report=dict(phase=phase,actual_optimizer_steps=steps,checkpoints=checkpoints,source=source,heads_digest=module_digest(stage))
        write_json(output/'readback.json',report)
    except BaseException as exc:
        save_failed_optimizer(optimizer,output,reason=repr(exc))
        with (output/'failure-head.pt').open('xb') as stream:
            torch.save(dict(stage_state=stage.state_dict(),optimizer_steps=dict(stage.optimizer_steps),
                source=source,phase=phase,code_digest=code_digest(),rng_state=torch.get_rng_state(),
                cuda_rng_state=torch.cuda.get_rng_state_all()),stream)
        raise
    stage.eval()
    return report


class EvidenceBatches:
    def __init__(self,events,*,seed,device):
        self.sampler=BalancedRunSampler([r for r in events if r['role']=='fit'],seed=seed)
        self.device=device; self.draw=0
    def __call__(self,stage):
        rows=self.sampler.next_group(16)
        # Alternate both paths, maintaining exactly8 samples per path per step.
        tokens=torch.stack([r['stream_tokens' if (self.draw+i)%2==0 else 'commit_tokens'] for i,r in enumerate(rows)]).to(self.device)
        self.draw+=16
        return stage.evidence_step(dict(tokens=tokens,target=torch.stack([r['target'] for r in rows]).to(self.device),
            mask=torch.stack([r['target_mask'] for r in rows]).to(self.device)))['loss']


@torch.no_grad()
def evidence_gate(stage,events,output):
    fit=[r for r in events if r['role']=='fit']; dev=[r for r in events if r['role']=='dev']
    if not fit or not dev:
        raise ValueError('Evidence fit/dev missing')
    device=next(stage.parameters()).device
    medians={}
    for sensor in {r['sensor_id'] for r in fit}:
        rows=[r for r in fit if r['sensor_id']==sensor]
        medians[sensor]=torch.tensor([float(torch.stack([r['target'][j] for r in rows if r['target_mask'][j]]).median())
                                     if any(r['target_mask'][j] for r in rows) else 0. for j in range(4)])
    absolute=[]; baseline=[]; saved=[]
    for event in dev:
        for path in ('stream','commit'):
            prediction=stage.heads.evidence(event[f'{path}_tokens'][None].to(device))[0].cpu()
            mask=event['target_mask']; target=event['target']
            absolute.extend((prediction-target).abs()[mask].tolist())
            baseline.extend((medians[event['sensor_id']]-target).abs()[mask].tolist())
            saved.append(dict(uid=event['uid'],path=path,prediction=prediction.tolist(),target=target.tolist(),mask=mask.tolist(),
                baseline=medians[event['sensor_id']].tolist(),subject_id=event['subject_id'],sensor_id=event['sensor_id']))
    mae=float(np.mean(absolute)); constant=float(np.mean(baseline))
    report=dict(passed=bool(constant>0 and mae<=.9*constant),masked_mae=mae,fit_median_baseline_mae=constant,
        improvement_fraction=None if constant==0 else 1-mae/constant,predictions=saved,
        baseline='per-sensor fit GT-run visible-prefix attribute median',heads_digest=module_digest(stage))
    groups={'all':saved}
    groups.update({f'sensor/{s}':[r for r in saved if r['sensor_id']==s] for s in sorted(medians)})
    groups.update({f'subject/{s}':[r for r in saved if r['subject_id']==s] for s in sorted({r['subject_id'] for r in saved})})
    report['group_attribute_mae']={}
    for name,rows in groups.items():
        attrs=[]
        for j in range(4):
            valid=[r for r in rows if r['mask'][j]]
            attrs.append(dict(attribute=j,count=len(valid),mae=None if not valid else float(np.mean([
                abs(r['prediction'][j]-r['target'][j]) for r in valid])),baseline_mae=None if not valid else float(np.mean([
                abs(r['baseline'][j]-r['target'][j]) for r in valid]))))
        report['group_attribute_mae'][name]=attrs
    write_json(Path(output)/'evidence-gate.json',report)
    return report


class PhysicalBatches:
    """Carry per-record prototype; do not force unequal counts into one batch state."""
    def __init__(self,index,*,device):
        self.device=device; self.records={}; self.cells=defaultdict(list)
        self.cursors={}; self.states={}; self.turn=0
        for row in index['records']:
            if row['role']!='fit':
                continue
            if file_sha(row['path'])!=row['sha256']:
                raise ValueError('physical encoder cache source SHA changed')
            payload=torch.load(row['path'],map_location='cpu',weights_only=False)
            labels=payload['labels'].numpy(); time=payload['timestamps'][:,0].numpy()
            valid=(labels>=0).all(1)&(labels[:,0]==labels[:,1])
            boundaries=payload['timestamps'].flatten().numpy()[1:][np.diff(payload['labels'].flatten().numpy())!=0]
            known=payload['labels'].flatten().numpy()
            boundary_valid=(known[1:]>=0)&(known[:-1]>=0)
            boundaries=payload['timestamps'].flatten().numpy()[1:][(np.diff(known)!=0)&boundary_valid]
            target=np.exp(-.5*((time[:,None]-boundaries[None,:])/.36)**2).max(1) if len(boundaries) else np.zeros(len(time))
            valid[1:]&=valid[:-1].copy(); valid[0]=False
            payload.update(physical_target=torch.from_numpy(target.astype(np.float32)),physical_valid=torch.from_numpy(valid))
            self.records[row['uid']]=payload
            self.cells[(row['metadata']['subject_id'],row['metadata']['sensor_id'])].append(row['uid'])
        self.subjects=sorted({key[0] for key in self.cells}); self.sensors=sorted({key[1] for key in self.cells})
    def __call__(self,stage):
        losses=[]
        for _ in range(16):
            j=self.turn; self.turn+=1
            cell=(self.subjects[j%len(self.subjects)],self.sensors[(j//len(self.subjects))%len(self.sensors)])
            sources=self.cells[cell]; uid=sources[(j//(len(self.subjects)*len(self.sensors)))%len(sources)]
            row=self.records[uid]; start=self.cursors.get(uid,0); end=min(start+64,len(row['radar']))
            if end-start==1 and start==0:
                raise ValueError('physical recording too short')
            batch=dict(tokens=row['radar'][start:end][None].to(self.device),mask=row['radar_mask'][start:end][None].to(self.device),
                target=row['physical_target'][start:end][None].to(self.device),valid=row['physical_valid'][start:end][None].to(self.device))
            if start:
                batch.update(initial_state=self.states[uid],previous_tokens=row['radar'][start-1:start].to(self.device),
                             previous_mask=row['radar_mask'][start-1:start].to(self.device))
            result=stage.physical_stream_step(batch)
            losses.append(result['loss']); self.states[uid]=result['next_state']
            self.cursors[uid]=0 if end==len(row['radar']) else end
        return torch.stack(losses).mean()
